import express, { type NextFunction, type Request, type Response } from 'express';
import path from 'node:path';
import fs from 'node:fs';
import { validateAgentInput } from '../shared/validate.ts';
import type { AgentDetail, AgentView, CompetitionView, DashboardData, EntrantView, PredictionsData, RoundDetail, RoundSummary } from '../shared/api.ts';
import type { Agent, AgentConfig, AppConfig, CategoryId } from '../shared/types.ts';
import { allCompetitionInfos, COMPETITIONS, getCompetition } from './competitions/index.ts';
import { config } from './config.ts';
import { newId, promptFor, type Store } from './db.ts';
import { HttpError } from './errors.ts';
import { placePrediction } from './predictions.ts';
import { anthropicAvailable } from './providers/anthropic.ts';
import { runRound } from './runner.ts';
import { agentInsights, agentStats, leaderboard } from './stats.ts';

const MAX_USER_AGENTS = 20;
const CATEGORIES: CategoryId[] = ['brain', 'research', 'strategy'];

const wrap = (fn: (req: Request, res: Response) => unknown | Promise<unknown>) => (req: Request, res: Response, next: NextFunction) =>
  Promise.resolve(fn(req, res)).catch(next);

export function createApp(store: Store) {
  const app = express();
  app.use(express.json({ limit: '50kb' }));
  // store.db is replaced by reset(), so always read it through this getter.
  const D = () => store.db;

  const agentView = (a: Agent): AgentView => ({ ...a, stats: agentStats(D(), a) });
  const engineKind = (a: Agent, version: number) =>
    a.kind === 'house' || (a.versions.find((v) => v.version === version)?.config ?? a.config).provider === 'demo' ? 'simulated' : 'live';
  const entrantView = (agentId: string, agentVersion: number): EntrantView => {
    const a = store.agent(agentId)!;
    const cfg = a.versions.find((v) => v.version === agentVersion)?.config ?? a.config;
    return { agentId, agentVersion, name: a.name, avatar: a.avatar, creator: a.creator, kind: a.kind, specialty: cfg.specialty, engine: engineKind(a, agentVersion), skill: a.skill };
  };
  const roundSummary = (r: import('../shared/types.ts').Round): RoundSummary => {
    const top = r.results.filter((x) => x.rank === 1);
    return {
      id: r.id, number: r.number, status: r.status, completedAt: r.completedAt,
      entrants: r.status === 'open' ? r.entrants.map((e) => entrantView(e.agentId, e.agentVersion)) : r.results.map((x) => ({
        agentId: x.agentId, agentVersion: x.agentVersion, name: x.agentName, avatar: x.avatar, creator: x.creator, kind: x.kind, specialty: x.specialty, engine: x.engine.kind,
      })),
      winners: top.map((x) => x.agentName), topScore: top[0]?.score ?? null,
    };
  };
  const competitionView = (id: string): CompetitionView => {
    const info = allCompetitionInfos().find((c) => c.id === id);
    if (!info) throw new HttpError(404, 'Competition not found.');
    const open = D().rounds.find((r) => r.competitionId === id && r.status === 'open');
    const past = D().rounds.filter((r) => r.competitionId === id && r.status === 'completed').sort((a, b) => b.number - a.number);
    const playable = !!getCompetition(id);
    const eligibility = D().agents.filter((a) => a.kind === 'user').map((a) => {
      const entered = !!open?.entrants.some((e) => e.agentId === a.id);
      if (!playable) return { agentId: a.id, eligible: false, entered, reason: 'This competition is not playable yet.' };
      if (!info.specialties.includes(a.config.specialty)) return { agentId: a.id, eligible: false, entered, reason: 'Its specialty is not accepted in this competition.' };
      if (a.config.provider === 'anthropic' && !anthropicAvailable()) return { agentId: a.id, eligible: false, entered, reason: 'It uses a live model, but no API key is configured on the server.' };
      return { agentId: a.id, eligible: true, entered };
    });
    return { info, currentRound: open ? roundSummary(open) : null, pastRounds: past.slice(0, 10).map(roundSummary), eligibility };
  };

  // ---------- config & profile ----------
  app.get('/api/config', (_req, res) => {
    const body: AppConfig = {
      mode: 'local-demo',
      providers: [
        { id: 'demo', label: 'Demo engine', available: true, model: 'Simulated (no AI model)', note: 'Results are generated by a simulator, not by an AI. Free and always available.' },
        {
          id: 'anthropic', label: 'Claude (Anthropic)', available: anthropicAvailable(), model: config.anthropicModel,
          note: anthropicAvailable() ? 'Live model called from the server with identical limits for every agent.' : 'Not configured. Add ANTHROPIC_API_KEY to the server .env file to enable it.',
        },
      ],
      startingPoints: config.startingPoints, minStake: config.minStake,
    };
    res.json(body);
  });

  app.get('/api/me', (_req, res) => res.json(D().user));
  app.put('/api/me', (req, res) => {
    const name = String(req.body?.name ?? '').trim();
    if (name.length < 2 || name.length > 24) throw new HttpError(400, 'Display name must be between 2 and 24 characters.');
    D().user.name = name;
    for (const a of D().agents) if (a.kind === 'user') a.creator = name;
    store.save();
    res.json(D().user);
  });
  app.post('/api/reset', (req, res) => {
    if (req.body?.confirm !== true) throw new HttpError(400, 'Confirmation required.');
    store.reset();
    res.json({ ok: true });
  });

  // ---------- agents ----------
  app.get('/api/agents', (req, res) => {
    const list = D().agents.filter((a) => (req.query.kind === 'house' ? a.kind === 'house' : a.kind === 'user'));
    res.json(list.map(agentView));
  });

  app.get('/api/agents/:id', (req, res) => {
    const a = store.agent(req.params.id);
    if (!a) throw new HttpError(404, 'Agent not found.');
    const body: AgentDetail = { ...agentView(a), insights: agentInsights(D(), a), systemPrompt: promptFor(a) };
    res.json(body);
  });

  const checkProvider = (c: AgentConfig) => {
    if (c.provider === 'anthropic' && !anthropicAvailable()) throw new HttpError(400, 'The live model is not configured on the server. Choose the Demo engine or add ANTHROPIC_API_KEY.');
  };

  app.post('/api/agents', (req, res) => {
    const v = validateAgentInput(req.body);
    if (!v.ok) throw new HttpError(400, v.error);
    checkProvider(v.value.config);
    if (D().agents.filter((a) => a.kind === 'user').length >= MAX_USER_AGENTS) throw new HttpError(400, `You can have at most ${MAX_USER_AGENTS} agents.`);
    const now = new Date().toISOString();
    const agent: Agent = {
      id: newId('agent'), ...v.value, kind: 'user', creator: D().user.name, createdAt: now, updatedAt: now, version: 1,
      versions: [{ version: 1, createdAt: now, note: 'Initial version', config: v.value.config }],
    };
    D().agents.push(agent);
    store.log(`You created ${agent.name}.`, `/agents/${agent.id}`);
    store.save();
    res.status(201).json(agentView(agent));
  });

  app.put('/api/agents/:id', (req, res) => {
    const a = store.agent(req.params.id);
    if (!a || a.kind !== 'user') throw new HttpError(404, 'Agent not found.');
    const v = validateAgentInput(req.body);
    if (!v.ok) throw new HttpError(400, v.error);
    const changed = JSON.stringify(v.value.config) !== JSON.stringify(a.config);
    if (changed) checkProvider(v.value.config);
    a.name = v.value.name; a.description = v.value.description; a.avatar = v.value.avatar; a.updatedAt = new Date().toISOString();
    if (changed) {
      a.version += 1;
      a.config = v.value.config;
      a.versions.push({ version: a.version, createdAt: a.updatedAt, note: String(req.body?.note ?? '').trim().slice(0, 140) || 'Settings updated', config: a.config });
      store.log(`You improved ${a.name} (now version ${a.version}).`, `/agents/${a.id}`);
    }
    store.save();
    res.json(agentView(a));
  });

  app.delete('/api/agents/:id', (req, res) => {
    const a = store.agent(req.params.id);
    if (!a || a.kind !== 'user') throw new HttpError(404, 'Agent not found.');
    if (D().predictions.some((p) => p.agentId === a.id && p.status === 'pending')) throw new HttpError(409, 'This agent has pending predictions. Wait for the round to finish.');
    for (const r of D().rounds) if (r.status === 'open') r.entrants = r.entrants.filter((e) => e.agentId !== a.id);
    D().agents = D().agents.filter((x) => x.id !== a.id);
    store.log(`You deleted ${a.name}. Its past results are kept in the history.`);
    store.save();
    res.json({ ok: true });
  });

  // ---------- competitions ----------
  app.get('/api/competitions', (_req, res) => res.json(allCompetitionInfos().map((c) => competitionView(c.id))));
  app.get('/api/competitions/:id', (req, res) => res.json(competitionView(req.params.id)));

  app.post('/api/competitions/:id/entries', (req, res) => {
    const def = getCompetition(req.params.id);
    if (!def) throw new HttpError(404, 'This competition is not playable yet.');
    const a = store.agent(String(req.body?.agentId));
    if (!a || a.kind !== 'user') throw new HttpError(404, 'Agent not found.');
    const view = competitionView(def.info.id).eligibility.find((e) => e.agentId === a.id)!;
    if (!view.eligible) throw new HttpError(400, `${a.name} cannot enter: ${view.reason}`);
    const round = store.openRound(def.info.id)!;
    if (round.entrants.some((e) => e.agentId === a.id)) throw new HttpError(409, `${a.name} is already entered.`);
    round.entrants.push({ agentId: a.id, agentVersion: a.version, enteredAt: new Date().toISOString() });
    store.log(`${a.name} entered ${def.info.name}.`, `/arena/${def.info.id}`);
    store.save();
    res.status(201).json(competitionView(def.info.id));
  });

  app.delete('/api/competitions/:id/entries/:agentId', (req, res) => {
    const round = store.openRound(req.params.id);
    if (!round) throw new HttpError(404, 'No open round.');
    const a = store.agent(req.params.agentId);
    if (a?.kind !== 'user') throw new HttpError(404, 'Agent not found.');
    if (D().predictions.some((p) => p.roundId === round.id && p.agentId === a.id && p.status === 'pending')) {
      throw new HttpError(409, 'You placed a prediction on this agent, so it cannot withdraw from the round.');
    }
    round.entrants = round.entrants.filter((e) => e.agentId !== req.params.agentId);
    store.save();
    res.json(competitionView(req.params.id));
  });

  app.post('/api/competitions/:id/run', wrap(async (req, res) => {
    const round = await runRound(store, req.params.id);
    res.json({ roundId: round.id });
  }));

  app.get('/api/rounds/:id', (req, res) => {
    const round = D().rounds.find((r) => r.id === req.params.id);
    if (!round) throw new HttpError(404, 'Round not found.');
    if (round.status !== 'completed') throw new HttpError(409, 'Results are published once the round is complete.');
    const def = getCompetition(round.competitionId)!;
    const body: RoundDetail = { round, info: def.info, tasks: def.tasks, results: round.results };
    res.json(body);
  });

  // ---------- leaderboard ----------
  app.get('/api/leaderboard', (req, res) => {
    const category = CATEGORIES.includes(req.query.category as CategoryId) ? (req.query.category as CategoryId) : 'brain';
    res.json(leaderboard(D(), category, req.query.includeHouse !== '0'));
  });

  // ---------- predictions ----------
  app.get('/api/predictions', (_req, res) => {
    const body: PredictionsData = { user: D().user, predictions: D().predictions, ledger: D().ledger.slice(0, 50) };
    res.json(body);
  });
  app.post('/api/predictions', (req, res) => {
    const p = placePrediction(store, req.body ?? {});
    store.save();
    res.status(201).json(p);
  });

  // ---------- dashboard ----------
  app.get('/api/dashboard', (_req, res) => {
    const mine = D().agents.filter((a) => a.kind === 'user');
    let bestRank: DashboardData['bestRank'] = null;
    for (const cat of CATEGORIES) {
      const rows = leaderboard(D(), cat, true);
      for (const row of rows) {
        if (row.kind === 'user' && (!bestRank || row.rank / rows.length < bestRank.rank / bestRank.of)) bestRank = { category: cat, rank: row.rank, of: rows.length, agentName: row.agentName };
      }
    }
    const open = D().rounds.filter((r) => r.status === 'open');
    const body: DashboardData = {
      user: D().user,
      agentCount: mine.length,
      activeCompetitions: open.length,
      wins: mine.reduce((n, a) => n + agentStats(D(), a).wins, 0),
      bestRank,
      upcoming: open.map((r) => ({ competitionId: r.competitionId, name: getCompetition(r.competitionId)!.info.name, category: getCompetition(r.competitionId)!.info.category, roundNumber: r.number, entrants: r.entrants.length })),
      activity: D().activity.slice(0, 8),
      featured: competitionView(COMPETITIONS[0].info.id),
      pendingPredictions: D().predictions.filter((p) => p.status === 'pending').length,
    };
    res.json(body);
  });

  // ---------- static client (production) ----------
  const dist = path.resolve('dist');
  if (fs.existsSync(dist)) {
    app.use(express.static(dist));
    app.get(/^\/(?!api\/).*/, (_req, res) => res.sendFile(path.join(dist, 'index.html')));
  }

  app.use('/api', (_req, _res, next) => next(new HttpError(404, 'Unknown API route.')));
  app.use((err: unknown, _req: Request, res: Response, _next: NextFunction) => {
    if (err instanceof HttpError) return res.status(err.status).json({ error: err.message });
    if ((err as any)?.type === 'entity.parse.failed') return res.status(400).json({ error: 'Invalid JSON.' });
    console.error(err);
    res.status(500).json({ error: 'Unexpected server error.' });
  });
  return app;
}
