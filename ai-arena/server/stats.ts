import type { AgentStats } from '../shared/api.ts';
import type { Agent, CategoryId, Db, Insight, LeaderboardRow, RunResult } from '../shared/types.ts';
import { allCompetitionInfos } from './competitions/index.ts';

const categoryOf = (_db: Db, competitionId: string): CategoryId =>
  allCompetitionInfos().find((c) => c.id === competitionId)?.category ?? 'brain';

const nameOf = (competitionId: string) => allCompetitionInfos().find((c) => c.id === competitionId)?.name ?? competitionId;

export function resultsForAgent(db: Db, agentId: string) {
  return db.rounds
    .filter((r) => r.status === 'completed')
    .flatMap((round) => round.results.filter((x) => x.agentId === agentId).map((result) => ({ round, result })));
}

const avg = (xs: number[]) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0);
const r1 = (n: number) => Math.round(n * 10) / 10;

export function agentStats(db: Db, agent: Agent): AgentStats {
  const runs = resultsForAgent(db, agent.id);
  const byCategory = {} as AgentStats['byCategory'];
  for (const cat of ['brain', 'research', 'strategy'] as CategoryId[]) {
    const rs = runs.filter((x) => categoryOf(db, x.round.competitionId) === cat);
    byCategory[cat] = {
      rounds: rs.length,
      wins: rs.filter((x) => x.result.rank === 1).length,
      avgScore: r1(avg(rs.map((x) => x.result.score))),
      bestScore: rs.length ? Math.max(...rs.map((x) => x.result.score)) : 0,
    };
  }
  const history = runs
    .map(({ round, result }) => ({
      roundId: round.id, competitionId: round.competitionId, competitionName: nameOf(round.competitionId), roundNumber: round.number,
      at: round.completedAt ?? round.createdAt, score: result.score, maxScore: result.maxScore, rank: result.rank,
      entrants: round.results.length, version: result.agentVersion, engine: result.engine.kind,
    }))
    .sort((a, b) => a.at.localeCompare(b.at));
  const versions = agent.versions.map((v) => {
    const rs = runs.filter((x) => x.result.agentVersion === v.version);
    return { version: v.version, rounds: rs.length, avgScorePct: rs.length ? r1(avg(rs.map((x) => (x.result.score / x.result.maxScore) * 100))) : null };
  });
  const wins = runs.filter((x) => x.result.rank === 1).length;
  return {
    rounds: runs.length, wins, winRate: runs.length ? r1((wins / runs.length) * 100) : 0,
    avgScorePct: r1(avg(runs.map((x) => (x.result.score / x.result.maxScore) * 100))),
    byCategory, history,
    versions,
    recentMistakes: [...runs].reverse().flatMap(({ round, result }) => result.mistakes.slice(0, 3).map((text) => ({ roundId: round.id, text }))).slice(0, 8),
  };
}

/**
 * Observations computed only from recorded results. Nothing here is generated by a model,
 * and the agent does not learn by itself: improving it means editing its settings (see version history).
 */
export function agentInsights(db: Db, agent: Agent): Insight[] {
  const runs = resultsForAgent(db, agent.id);
  if (!runs.length) return [{ tone: 'info', text: 'No completed competitions yet. Insights appear after your first round.' }];
  const out: Insight[] = [];
  const simulated = runs.filter((x) => x.result.engine.kind === 'simulated').length;
  if (simulated) out.push({ tone: 'info', text: `${simulated} of ${runs.length} run(s) came from the demo engine. Simulated results are random draws and say nothing about the quality of your agent's instructions.` });

  const tagStats = new Map<string, { ok: number; n: number }>();
  for (const { result } of runs) for (const a of result.answers) {
    if (a.correct === null) continue;
    const t = tagStats.get(a.tag) ?? { ok: 0, n: 0 };
    t.n++; if (a.correct) t.ok++;
    tagStats.set(a.tag, t);
  }
  for (const [tag, t] of tagStats) {
    if (t.n < 2) continue;
    const pct = Math.round((t.ok / t.n) * 100);
    if (pct >= 80) out.push({ tone: 'good', text: `Strong on "${tag}" questions: ${t.ok}/${t.n} correct (${pct}%).` });
    else if (pct <= 40) out.push({ tone: 'warn', text: `Struggles with "${tag}" questions: ${t.ok}/${t.n} correct (${pct}%).` });
  }

  const crit = new Map<string, { label: string; earned: number; max: number }>();
  for (const { result, round } of runs) {
    if (categoryOf(db, round.competitionId) !== 'research') continue;
    for (const c of result.criteria) {
      const t = crit.get(c.id) ?? { label: c.label, earned: 0, max: 0 };
      t.earned += c.earned; t.max += c.max; crit.set(c.id, t);
    }
  }
  if (crit.size) {
    const ranked = [...crit.values()].map((c) => ({ ...c, pct: c.earned / c.max })).sort((a, b) => a.pct - b.pct);
    const worst = ranked[0], best = ranked[ranked.length - 1];
    if (worst.pct < 0.7) out.push({ tone: 'warn', text: `Weakest research criterion: ${worst.label} (${Math.round(worst.pct * 100)}% of available points).` });
    if (best.pct >= 0.8) out.push({ tone: 'good', text: `Best research criterion: ${best.label} (${Math.round(best.pct * 100)}% of available points).` });
  }

  const formatFails = runs.reduce((n, { result }) => n + result.answers.filter((a) => a.correct !== null && a.parsed === null).length, 0);
  if (formatFails) out.push({ tone: 'warn', text: `${formatFails} answer(s) were not scored because they did not end with an "ANSWER:" line.` });

  const scored = agentStats(db, agent).versions.filter((v) => v.avgScorePct !== null);
  if (scored.length >= 2) {
    const a = scored[scored.length - 2], b = scored[scored.length - 1];
    const d = r1((b.avgScorePct as number) - (a.avgScorePct as number));
    out.push({ tone: 'info', text: `Version ${b.version} averages ${b.avgScorePct}% versus ${a.avgScorePct}% for version ${a.version} (${d >= 0 ? '+' : ''}${d} points). Small samples are noisy.` });
  }
  if (out.length === (simulated ? 1 : 0)) out.push({ tone: 'info', text: 'Not enough data yet for specific observations. Run a few more rounds.' });
  return out;
}

export function leaderboard(db: Db, category: CategoryId, includeHouse: boolean): LeaderboardRow[] {
  const ids = new Set(allCompetitionInfos().filter((c) => c.category === category).map((c) => c.id));
  const groups = new Map<string, RunResult[]>();
  for (const round of db.rounds) {
    if (round.status !== 'completed' || !ids.has(round.competitionId)) continue;
    for (const r of round.results) {
      if (!includeHouse && r.kind === 'house') continue;
      groups.set(r.agentId, [...(groups.get(r.agentId) ?? []), r]);
    }
  }
  // Wins are always counted against the full field, even when house bots are hidden from the table.
  const rows = [...groups.entries()].map(([agentId, rs]) => {
    const last = rs[rs.length - 1];
    const wins = rs.filter((x) => x.rank === 1).length;
    const kinds = new Set(rs.map((x) => x.engine.kind));
    return {
      rank: 0, agentId, agentName: last.agentName, avatar: last.avatar, creator: last.creator, kind: last.kind, specialty: last.specialty,
      avgScore: r1(avg(rs.map((x) => x.score))), bestScore: Math.max(...rs.map((x) => x.score)), wins, rounds: rs.length,
      winRate: r1((wins / rs.length) * 100), engine: (kinds.size > 1 ? 'mixed' : [...kinds][0]) as LeaderboardRow['engine'],
    };
  });
  rows.sort((a, b) => b.avgScore - a.avgScore || b.wins - a.wins || a.agentName.localeCompare(b.agentName));
  rows.forEach((r, i) => {
    const p = rows[i - 1];
    r.rank = p && p.avgScore === r.avgScore && p.wins === r.wins ? p.rank : i + 1;
  });
  return rows;
}
