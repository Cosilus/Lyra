import { useEffect, useState } from 'react';
import type { AppConfig, User } from '../../shared/types.ts';
import { Badge, Button, ErrorBox, Modal, Notice, PageHeader, Spinner } from '../components/ui.tsx';
import { useToast } from '../components/Toast.tsx';
import { api, useApi } from '../lib/api.ts';
import { fmt } from '../lib/format.ts';

export default function Profile() {
  const toast = useToast();
  const me = useApi<User>('/api/me');
  const cfg = useApi<AppConfig>('/api/config');
  const [name, setName] = useState('');
  const [saving, setSaving] = useState(false);
  const [confirm, setConfirm] = useState(false);
  useEffect(() => { if (me.data) setName(me.data.name); }, [me.data]);
  if ((me.loading && !me.data) || (cfg.loading && !cfg.data)) return <Spinner />;
  if (me.error || cfg.error || !me.data || !cfg.data) return <ErrorBox message={me.error ?? cfg.error ?? 'Could not load profile.'} onRetry={() => { me.reload(); cfg.reload(); }} />;

  const save = async () => {
    setSaving(true);
    try { await api('PUT', '/api/me', { name }); toast('Profile saved.'); me.reload(); } catch (e: any) { toast(e.message, true); } finally { setSaving(false); }
  };
  const reset = async () => {
    try { await api('POST', '/api/reset', { confirm: true }); toast('Demo data reset.'); setConfirm(false); me.reload(); } catch (e: any) { toast(e.message, true); }
  };

  return (
    <>
      <PageHeader title="Profile" subtitle="Your local demo player and the engines available on this server." />
      <div className="grid gap-6 lg:grid-cols-2">
        <section className="card space-y-5 p-5 md:p-6">
          <div className="flex items-center justify-between"><div className="label">Player</div><Badge tone="warn">Local demo mode</Badge></div>
          <div><label className="label" htmlFor="pname">Display name</label><div className="mt-2 flex gap-2"><input id="pname" className="input" value={name} maxLength={24} onChange={(e) => setName(e.target.value)} /><Button variant="primary" loading={saving} onClick={save}>Save</Button></div></div>
          <div className="rounded-lg border border-line bg-bg p-4"><div className="label">Virtual points</div><div className="mt-1 text-2xl font-semibold tabular-nums">{fmt(me.data.points)}</div></div>
          <Notice tone="warn">There is no sign-in. This is a single local player whose data is stored in a file on this computer. It is a demonstration, not a secure account, and it is not suitable for several users.</Notice>
          <Button variant="danger" onClick={() => setConfirm(true)}>Reset all demo data</Button>
        </section>

        <section className="card space-y-4 p-5 md:p-6">
          <div className="label">Model engines</div>
          {cfg.data.providers.map((p) => (
            <div key={p.id} className="rounded-lg border border-line p-4">
              <div className="flex items-center justify-between gap-2"><span className="text-sm font-medium">{p.label}</span>{p.available ? <Badge tone="accent">Available</Badge> : <Badge tone="warn">Not configured</Badge>}</div>
              <div className="mt-1 text-xs text-muted">{p.model}</div><p className="mt-2 text-xs leading-relaxed text-muted">{p.note}</p>
            </div>))}
          <div className="label pt-2">What is simulated</div>
          <ul className="space-y-1.5 text-xs leading-relaxed text-muted">
            <li>• Demo engine results: generated by a seeded random simulator, not by an AI. The same engine plays the house bots, whose skill level is published.</li>
            <li>• Opponents: only house bots exist. There are no other human players in this local prototype.</li>
          </ul>
        </section>
      </div>
      <Modal open={confirm} title="Reset all demo data?" onClose={() => setConfirm(false)}>
        <p>This deletes your agents, results, predictions and points and starts over with {fmt(cfg.data.startingPoints)} points. It cannot be undone.</p>
        <div className="mt-5 flex justify-end gap-2"><Button onClick={() => setConfirm(false)}>Cancel</Button><Button variant="danger" onClick={reset}>Reset</Button></div>
      </Modal>
    </>
  );
}
